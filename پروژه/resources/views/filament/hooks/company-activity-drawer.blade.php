<script>
(() => {
    const stage = document.getElementById('hm-company-activity-stage');

    if (!stage || stage.dataset.initialized === 'true') return;

    stage.dataset.initialized = 'true';

    const drawerSelector = '.fi-modal.fi-modal-slide-over > .fi-modal-window-ctn > .fi-modal-window';
    const sync = () => {
        const drawer = [...document.querySelectorAll(drawerSelector)]
            .find((element) => element.getClientRects().length > 0 && getComputedStyle(element).visibility !== 'hidden');

        if (!drawer || window.innerWidth < 1024) {
            stage.hidden = true;
            return;
        }

        const rect = drawer.getBoundingClientRect();
        const drawerOnRight = (rect.left + (rect.width / 2)) > (window.innerWidth / 2);
        const left = drawerOnRight ? 0 : rect.right;
        const width = Math.max(0, drawerOnRight ? rect.left : window.innerWidth - rect.right);

        const nextLeft = left + 'px';
        const nextWidth = width + 'px';

        if (stage.style.left !== nextLeft) stage.style.left = nextLeft;
        if (stage.style.width !== nextWidth) stage.style.width = nextWidth;

        stage.hidden = width < 180;
    };

    const syncDuringTransition = () => {
        let frames = 0;
        const tick = () => {
            sync();
            if (++frames < 36) requestAnimationFrame(tick);
        };
        requestAnimationFrame(tick);
    };

    const observer = new MutationObserver(sync);
    observer.observe(document.body, {
        subtree: true,
        childList: true,
        attributes: true,
        attributeFilter: ['style', 'class', 'aria-hidden'],
    });

    document.addEventListener('open-modal', syncDuringTransition, true);
    document.addEventListener('close-modal', syncDuringTransition, true);
    window.addEventListener('resize', syncDuringTransition);
    document.addEventListener('livewire:navigated', syncDuringTransition);

    sync();
})();
</script>
